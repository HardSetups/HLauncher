const I18nContext = createContext({ lang: 'tr', t: (k) => k, setLang: () => {} });

export function I18nProvider({ lang, setLang, children }) {
  // <html lang> dile uysun: CSS büyük harf dönüşümü ve ekran okuyucular için
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const t = useCallback((key, params) => {
    let text = DICTS[lang]?.[key] ?? DICTS.tr[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
    }
    return text;
  }, [lang]);
  return <I18nContext.Provider value={{ lang, t, setLang }}>{children}</I18nContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components
export const useI18n = () => useContext(I18nContext);
